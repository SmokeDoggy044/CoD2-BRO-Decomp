#!/usr/bin/env python3
"""Generates the cover anim-set fillers (src/engine/levelscript/bro_scr_cover_animsets.inc).

BroScr_CoverLeftAnimSet_1..7 / BroScr_CoverRightAnimSet_1..7 are straight-line code that
fills an anim-set record (the stack argument) from float constants and anim handles in
.data: every store is one of
  movss xmm0,[const] / xorps xmm0,xmm0 ; movss [out+N],xmm0          (a float word)
  mov reg,[global] ; mov [out+N],reg                                  (an anim handle)
  mov [out+N],imm                                                     (a hash)
  a float vector built in stack temporaries, copied through ECX to [out+0x30+N].
This script replays each body (only those instruction forms; anything else is an error),
keeps the store order and writes one C function per member, which copies the words from
their title addresses (so leaf tests that vary the constants still compare alike).

usage: tools/gen_cover_animsets.py [--dry-run]
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import fnpack  # noqa: E402
import engine_src

ROOT = fnpack.ROOT
OUT = engine_src.path("bro_scr_cover_animsets.inc")
MEMBERS = [
    ("BroScr_CoverLeftAnimSet_6", 0x0018c710), ("BroScr_CoverLeftAnimSet_1", 0x0018c800),
    ("BroScr_CoverLeftAnimSet_2", 0x0018c990), ("BroScr_CoverLeftAnimSet_3", 0x0018cb20),
    ("BroScr_CoverLeftAnimSet_4", 0x0018cc90), ("BroScr_CoverLeftAnimSet_7", 0x0018ce00),
    ("BroScr_CoverLeftAnimSet_5", 0x0018cef0),
    ("BroScr_CoverRightAnimSet_1", 0x0018d050), ("BroScr_CoverRightAnimSet_2", 0x0018d1e0),
    ("BroScr_CoverRightAnimSet_3", 0x0018d370), ("BroScr_CoverRightAnimSet_4", 0x0018d4f0),
    ("BroScr_CoverRightAnimSet_7", 0x0018d660), ("BroScr_CoverRightAnimSet_6", 0x0018d750),
    ("BroScr_CoverRightAnimSet_5", 0x0018d840),
]

H = r"(0x[0-9a-f]+)"


def off(text):
    """[eax] / [eax+0x24] -> 0 / 0x24."""
    m = re.fullmatch(r"\[(\w+)(?:\+" + H + r")?\]", text)
    return m.group(1), int(m.group(2), 16) if m.group(2) else 0


def replay(image, name, va):
    """The stores in order: (offset, ('global', addr) | ('zero',) | ('imm', value))."""
    regs, stack, stores, bases = {}, {}, [], {}
    for addr, n, text in fnpack.disassemble(image, va, 0x200):
        t = re.sub(r"<[^>]*>", "", text).replace("DWORD PTR ", "")
        if t == "ret":
            return stores
        if re.fullmatch(r"(sub|add) esp," + H, t) or t.startswith("lea ecx,[ecx"):  # frame / alignment nops
            continue
        m = re.fullmatch(r"mov eax,\[esp\+" + H + r"\]", t)
        if m:
            bases["eax"] = 0
            continue
        m = re.fullmatch(r"lea (\w+),\[eax\+" + H + r"\]", t)
        if m:
            bases[m.group(1)] = int(m.group(2), 16)
            continue
        m = re.fullmatch(r"movss (xmm\d),ds:" + H, t)
        if m:
            regs[m.group(1)] = ("global", int(m.group(2), 16))
            continue
        m = re.fullmatch(r"xorps (xmm\d),\1", t)
        if m:
            regs[m.group(1)] = ("zero",)
            continue
        m = re.fullmatch(r"mov (e[a-d]x),ds:" + H, t)
        if m:
            regs[m.group(1)] = ("global", int(m.group(2), 16))
            continue
        m = re.fullmatch(r"movss (\[esp(?:\+0x[0-9a-f]+)?\]),(xmm\d)", t)
        if m:
            stack[off(m.group(1))[1]] = regs[m.group(2)]
            continue
        m = re.fullmatch(r"mov (e[a-d]x),(\[esp(?:\+0x[0-9a-f]+)?\])", t)
        if m:
            regs[m.group(1)] = stack[off(m.group(2))[1]]
            continue
        m = re.fullmatch(r"(?:movss|mov) (\[\w+(?:\+0x[0-9a-f]+)?\]),(\w+)", t)
        if m:
            base, o = off(m.group(1))
            src = m.group(2)
            if base not in bases:
                sys.exit(f"{name} {addr:08x}: store through {base}: {t}")
            value = ("imm", int(src, 16)) if src.startswith("0x") else regs[src]
            stores.append((bases[base] + o, value))
            continue
        sys.exit(f"{name} {addr:08x}: unexpected instruction: {t}")
    sys.exit(f"{name}: no ret")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    image = fnpack.Image()
    out = ["// Generated by tools/gen_cover_animsets.py - do not edit.", ""]
    for name, va in MEMBERS:
        stores = replay(image, name, va)
        out.append(f"// 0x{va:08x}: {len(stores)} words.")
        out.append(f"uint8_t* XB_CDECL {name}(uint8_t* set) {{")
        for o, value in stores:
            if value[0] == "global":
                rhs = f"title_global<uint32_t>(0x{value[1]:08x})"
            elif value[0] == "zero":
                rhs = "0"
            else:
                rhs = f"0x{value[1]:08x}u"
            out.append(f"    animset_word(set, 0x{o:x}) = {rhs};")
        out.append("    return set;")
        out.append("}")
        out.append("")
    text = "\n".join(out)
    if a.dry_run:
        print(text)
    else:
        OUT.write_text(text)
        print(f"wrote {OUT} ({len(MEMBERS)} functions)")


if __name__ == "__main__":
    main()
