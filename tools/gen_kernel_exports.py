#!/usr/bin/env python3
"""Generate xbox/kernel_exports.inc from the xboxkrnl ordinal list and xboxkrnl.h.

Each export becomes one line:
    KEXPORT(ordinal, Name, KIND, stack_bytes)
KIND is STDCALL, FASTCALL, CDECL, DATA or UNKNOWN (no prototype in the header).
stack_bytes is how many argument bytes the callee pops (0 for CDECL/DATA/UNKNOWN);
for FASTCALL the first two 32-bit arguments travel in ECX/EDX and are not counted.

Usage: gen_kernel_exports.py <ordinals.txt> <xboxkrnl.h> <output.inc>
"""
import re
import sys

# Header declarations that are wrong or missing a calling convention.
OVERRIDES = {
    "HalBootSMCVideoMode": "DATA",  # declared as a function, exported as a DWORD
}

WIDE_TYPES = {"LARGE_INTEGER", "ULARGE_INTEGER", "LONGLONG", "ULONGLONG"}
QUALIFIERS = {"IN", "OUT", "OPTIONAL", "CONST", "const", "volatile", "struct"}


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def param_bytes(param):
    if "*" in param or "[" in param:
        return 4
    words = [w for w in re.findall(r"\w+", param) if w not in QUALIFIERS]
    return 8 if words and words[0] in WIDE_TYPES else 4


def parse_header(path):
    text = strip_comments(open(path, encoding="latin-1").read())
    decls = {}
    for m in re.finditer(r"\bXBAPI\b([^;{]*?)(\(([^()]*)\))?\s*;", text, flags=re.S):
        head, params = m.group(1), m.group(3)
        if params is None:
            name = re.findall(r"(\w+)\s*(?:\[[^\]]*\])?\s*$", head.strip())
            if name:
                decls[name[0]] = ("DATA", 0)
            continue
        name = re.findall(r"(\w+)\s*$", head.strip())
        if not name:
            continue
        name = name[0]
        if re.search(r"\bFASTCALL\b", head):
            kind = "FASTCALL"
        elif re.search(r"\bCDECL\b", head) or "..." in params:
            kind = "CDECL"
        else:
            kind = "STDCALL"  # NTAPI, or no convention given: the kernel default
        plist = [p.strip() for p in params.split(",")]
        plist = [p for p in plist if p and p != "void" and p != "VOID"]
        sizes = [param_bytes(p) for p in plist]
        if kind == "FASTCALL":
            regs = 0
            stack = 0
            for s in sizes:
                if s == 4 and regs < 2:
                    regs += 1
                else:
                    stack += s
            decls[name] = (kind, stack)
        elif kind == "CDECL":
            decls[name] = (kind, 0)
        else:
            decls[name] = (kind, sum(sizes))
    return decls


def main():
    ordinals_path, header_path, out_path = sys.argv[1:4]
    decls = parse_header(header_path)
    lines = [
        "// Generated by tools/gen_kernel_exports.py - do not edit.",
        "// KEXPORT(ordinal, Name, KIND, stack_bytes)",
    ]
    missing = []
    for line in open(ordinals_path):
        parts = line.split()
        if len(parts) < 2:
            continue
        ordinal, name = int(parts[0]), parts[1]
        if name in OVERRIDES:
            kind, stack = OVERRIDES[name], 0
        elif name in decls:
            kind, stack = decls[name]
        else:
            kind, stack = "UNKNOWN", 0
            missing.append(name)
        lines.append(f"KEXPORT({ordinal}, {name}, {kind}, {stack})")
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    if missing:
        print(f"{len(missing)} exports without a prototype: {', '.join(missing)}")


if __name__ == "__main__":
    main()
